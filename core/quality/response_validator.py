
"""
TRUJARVIS - Response Validator

Performs basic structural quality checks
on responses generated by the AI engine.
"""


class ResponseValidator:
    """Validates basic response completeness and structure."""

    @staticmethod
    def validate(response: str) -> dict:
        """
        Validate an AI-generated response.

        Returns:
            dict: Validation status, errors and warnings.
        """

        errors = []
        warnings = []

        # Check response type
        if not isinstance(response, str):
            return {
                "valid": False,
                "errors": ["Response must be a string."],
                "warnings": [],
            }

        # Check empty response
        if not response.strip():
            errors.append("Response is empty.")

        if errors:
            return {
                "valid": False,
                "errors": errors,
                "warnings": warnings,
            }

        cleaned_response = response.strip()

        # Check incomplete code fences
        code_fence_count = cleaned_response.count("```")

        if code_fence_count % 2 != 0:
            warnings.append(
                "Possible incomplete Markdown code block."
            )

        # Check common truncation indicators
        truncation_markers = [
            "[TRUNCATED]",
            "...(truncated)",
            "[OUTPUT CUT OFF]",
        ]

        for marker in truncation_markers:
            if marker.lower() in cleaned_response.lower():
                warnings.append(
                    "Possible response truncation detected."
                )
                break

        return {
            "valid": len(errors) == 0,
            "errors": errors,
            "warnings": warnings,
        }
